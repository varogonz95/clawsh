#!/usr/bin/env python3
"""Enforces the attribution settings in .claude/settings.json (+ settings.local.json).

  attribution.commit set (e.g. "")  no Co-Authored-By: Claude / Claude-Session trailers
                                    or "Generated with Claude Code" lines in commits
  attribution.pr set (e.g. "")      no "Generated by/with Claude Code" footer on PRs,
                                    issues, comments and reviews
  attribution.sessionUrl: false     no claude.ai/code/session_... links anywhere
  attribution: false, or            all of the above
  includeCoAuthoredBy: false

Claude Code itself only applies these to the commits and PRs it writes. The hosted
GitHub MCP server and the "Create PR" button add their own footer and session link
regardless, so this script closes the gaps:

  (no args)       Claude Code hook (PreToolUse/PostToolUse on mcp__github__* and Bash):
                  refuses GitHub calls and pushes that carry attribution, and makes
                  Claude clean up what the GitHub server adds or what a commit got.
  enforce-github  run by .github/workflows/attribution.yml: strips attribution from
                  the PR, issue, comment or review that triggered it, and fails when
                  a PR's commits carry trailers (history can't be rewritten there).
"""
import json
import os
import re
import subprocess
import sys
import urllib.request

FOOTER = re.compile(r"^(?:[^\w\n]|_)*Generated (by|with) \[?Claude Code.*$", re.IGNORECASE | re.MULTILINE)
SESSION_URL = re.compile(r"https?://claude\.ai/code/session_[A-Za-z0-9]+")
TRAILER = re.compile(r"^\s*(Co-Authored-By:\s*Claude\b|Claude-Session:).*$", re.IGNORECASE | re.MULTILINE)


def git(*args):
    return subprocess.run(["git", *args], capture_output=True, text=True).stdout


def root():
    return os.environ.get("CLAUDE_PROJECT_DIR") or git("rev-parse", "--show-toplevel").strip() or "."


class Rules:
    def __init__(self, settings):
        a = settings.get("attribution")
        off = a is False or settings.get("includeCoAuthoredBy") is False
        a = a if isinstance(a, dict) else {}
        self.commit = off or "commit" in a
        self.pr = off or "pr" in a
        self.session = off or a.get("sessionUrl") is False

    def any(self):
        return self.commit or self.pr or self.session


def load_rules(text=None):
    """Rules from the project settings, local settings overriding project ones."""
    if text is not None:
        sources = [text]
    else:
        paths = [os.path.join(root(), ".claude", f) for f in ("settings.json", "settings.local.json")]
        sources = [open(p).read() for p in paths if os.path.exists(p)]
    settings = {}
    for src in sources:
        try:
            data = json.loads(src)
        except ValueError:
            continue
        for key in ("attribution", "includeCoAuthoredBy"):
            if key in data:
                if isinstance(data[key], dict) and isinstance(settings.get(key), dict):
                    settings[key] = {**settings[key], **data[key]}
                else:
                    settings[key] = data[key]
    return Rules(settings)


def text_findings(text, rules):
    """Attribution in a PR, issue, comment or review body."""
    found = []
    if rules.pr:
        found += [m.group(0).strip() for m in FOOTER.finditer(text)]
    if rules.session:
        found += SESSION_URL.findall(text)
    return found


def commit_findings(message, rules):
    found = []
    if rules.commit:
        found += [m.group(0).strip() for m in TRAILER.finditer(message)]
        found += [m.group(0).strip() for m in FOOTER.finditer(message)]
    if rules.session:
        found += SESSION_URL.findall(message)
    return found


def strip(text, rules):
    """Body with forbidden footers and session links removed."""
    lines = text.split("\n")
    out = []
    for line in lines:
        if rules.pr and FOOTER.fullmatch(line):
            continue
        if rules.session and SESSION_URL.search(line):
            line = SESSION_URL.sub("", line).rstrip()
            if not re.sub(r"[\W_]", "", line):
                continue
        out.append(line)
    if out != lines:
        # The footer's "---" separator and trailing blank lines are left over.
        while out and out[-1].strip() in ("", "---"):
            out.pop()
    return "\n".join(out)


def strings(value):
    if isinstance(value, str):
        yield value
    elif isinstance(value, dict):
        for v in value.values():
            yield from strings(v)
    elif isinstance(value, list):
        for v in value:
            yield from strings(v)


def log_findings(*rev_args, rules):
    """Commits in the given range whose messages carry forbidden attribution."""
    log = git("log", "--format=%h%x1f%B%x1e", *rev_args)
    bad = []
    for entry in filter(None, (e.strip() for e in log.split("\x1e"))):
        sha, _, msg = entry.partition("\x1f")
        found = commit_findings(msg, rules)
        if found:
            bad.append(f"{sha}: {'; '.join(found)}")
    return bad


# --- Claude Code hook ---------------------------------------------------------

UNEDITABLE = {"mcp__github__add_comment_to_pending_review", "mcp__github__add_reply_to_pull_request_comment"}
FIX_AFTER = {
    "mcp__github__create_pull_request": "mcp__github__update_pull_request with the same body",
    "mcp__github__add_issue_comment": "mcp__github__update_issue_comment (comment id from the result) with the same body",
    "mcp__github__issue_write": "mcp__github__issue_write method update with the same body",
}


def deny(reason):
    print(json.dumps({"hookSpecificOutput": {
        "hookEventName": "PreToolUse", "permissionDecision": "deny", "permissionDecisionReason": reason}}))


def block(reason):
    print(json.dumps({"decision": "block", "reason": reason}))


def hook():
    event = json.load(sys.stdin)
    tool, args, name = event.get("tool_name", ""), event.get("tool_input") or {}, event.get("hook_event_name")
    if tool == "Bash" and not re.search(r"\bgit\b", args.get("command", "")):
        return
    rules = load_rules()
    if not rules.any():
        return

    if tool == "Bash":
        cmd = args.get("command", "")
        if name == "PreToolUse" and re.search(r"\bgit\b[^;&|]*\bpush\b", cmd):
            bad = log_findings("HEAD", "--not", "--remotes", rules=rules)
            if bad:
                deny("Attribution in unpushed commits, which .claude/settings.json forbids. Reword them "
                     "(they're not pushed, so rewriting is safe), then push:\n" + "\n".join(bad))
        elif name == "PostToolUse" and re.search(r"\bgit\b[^;&|]*\bcommit\b", cmd):
            found = commit_findings(git("log", "-1", "--format=%B"), rules)
            if found:
                block("The commit just made carries attribution that .claude/settings.json forbids ("
                      + "; ".join(found) + "). Amend its message now, before pushing.")
        return

    if name == "PreToolUse":
        found = {f for s in strings(args) for f in text_findings(s, rules) + commit_findings(s, rules)}
        if found:
            deny("Attribution that .claude/settings.json forbids: " + "; ".join(sorted(found))
                 + ". Remove it and retry.")
        elif rules.pr and (args.get("body") or "").strip() and (
            tool in UNEDITABLE
            or (tool == "mcp__github__pull_request_review_write" and args.get("method") in ("create", "submit_pending"))
        ):
            deny("The GitHub server appends a Claude attribution footer to this text, which .claude/settings.json "
                 "forbids, and the tools can't edit it afterwards. Give the text to the user to post instead.")
    elif name == "PostToolUse" and tool in FIX_AFTER and (rules.pr or rules.session):
        if tool == "mcp__github__issue_write" and args.get("method") != "create":
            return
        block("The GitHub server appends a Claude attribution footer and session link to what it creates, which "
              f".claude/settings.json forbids. Remove them now: call {FIX_AFTER[tool]} you sent, then read the "
              "object back and confirm they're gone.")


# --- GitHub workflow ----------------------------------------------------------

def api(method, path, body):
    req = urllib.request.Request(
        os.environ.get("GITHUB_API_URL", "https://api.github.com") + path,
        method=method,
        data=json.dumps(body).encode(),
        headers={"Authorization": "Bearer " + os.environ["GITHUB_TOKEN"],
                 "Accept": "application/vnd.github+json", "Content-Type": "application/json"},
    )
    with urllib.request.urlopen(req) as resp:
        return resp.status


def enforce_github():
    event_name = os.environ["GITHUB_EVENT_NAME"]
    event = json.load(open(os.environ["GITHUB_EVENT_PATH"]))
    repo = "/repos/" + os.environ["GITHUB_REPOSITORY"]
    # The default branch's settings decide, so a PR can't switch enforcement off for itself.
    base = git("show", f"origin/{event['repository']['default_branch']}:.claude/settings.json")
    rules = load_rules(base) if base else load_rules()

    routes = {
        "pull_request": ("pull_request", lambda o: ("PATCH", f"{repo}/pulls/{o['number']}")),
        "issues": ("issue", lambda o: ("PATCH", f"{repo}/issues/{o['number']}")),
        "issue_comment": ("comment", lambda o: ("PATCH", f"{repo}/issues/comments/{o['id']}")),
        "pull_request_review": (
            "review", lambda o: ("PUT", f"{repo}/pulls/{event['pull_request']['number']}/reviews/{o['id']}")),
        "pull_request_review_comment": ("comment", lambda o: ("PATCH", f"{repo}/pulls/comments/{o['id']}")),
    }
    key, route = routes[event_name]
    obj = event[key]
    body = obj.get("body") or ""
    cleaned = strip(body, rules)
    if cleaned != body:
        method, path = route(obj)
        api(method, path, {"body": cleaned})
        print(f"Removed from the {event_name} body: " + "; ".join(text_findings(body, rules)))

    if event_name == "pull_request":
        pr = event["pull_request"]
        bad = log_findings(f"{pr['base']['sha']}..{pr['head']['sha']}", rules=rules)
        for b in bad:
            print(f"::error::Commit {b} carries attribution that .claude/settings.json forbids; reword it")
        if bad:
            sys.exit(1)


if __name__ == "__main__":
    if sys.argv[1:] == ["enforce-github"]:
        enforce_github()
    else:
        hook()

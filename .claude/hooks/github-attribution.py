#!/usr/bin/env python3
"""Keeps Claude attribution out of GitHub objects created through the mcp__github__ tools.

The hosted GitHub MCP server appends a "Generated by Claude Code" footer (with a
session link) to bodies it creates, regardless of the attribution settings in
settings.json, and CLAUDE.md forbids attribution in any repository object.

PreToolUse:  deny any call whose text already carries attribution, and deny
             creating text that the tools can't edit afterwards (review bodies,
             review comments, review replies).
PostToolUse: after creating a PR, issue or issue comment, make Claude rewrite
             the body without the footer through the matching update tool
             (edits don't get the footer appended) and read it back.
"""
import json
import re
import sys

ATTRIBUTION = re.compile(
    r"Generated (by|with) \[?Claude Code|claude\.ai/code/session_|Co-Authored-By:\s*Claude|Claude-Session:",
    re.IGNORECASE,
)

# Tools that create text the GitHub tools can't edit later.
UNEDITABLE = {
    "mcp__github__add_comment_to_pending_review",
    "mcp__github__add_reply_to_pull_request_comment",
}

# Created object -> how to strip the footer afterwards.
FIX_AFTER = {
    "mcp__github__create_pull_request": "mcp__github__update_pull_request with the same body",
    "mcp__github__add_issue_comment": "mcp__github__update_issue_comment (comment id from the result) with the same body",
    "mcp__github__issue_write": "mcp__github__issue_write method update with the same body",
}


def strings(value):
    if isinstance(value, str):
        yield value
    elif isinstance(value, dict):
        for v in value.values():
            yield from strings(v)
    elif isinstance(value, list):
        for v in value:
            yield from strings(v)


def deny(reason):
    print(json.dumps({"hookSpecificOutput": {
        "hookEventName": "PreToolUse",
        "permissionDecision": "deny",
        "permissionDecisionReason": reason,
    }}))


def main():
    event = json.load(sys.stdin)
    tool = event.get("tool_name", "")
    args = event.get("tool_input") or {}

    if event.get("hook_event_name") == "PreToolUse":
        if any(ATTRIBUTION.search(s) for s in strings(args)):
            deny("No Claude attribution in repository objects (CLAUDE.md, Branches). "
                 "Remove the footer, trailer or session link and retry.")
        elif (args.get("body") or "").strip() and (
            tool in UNEDITABLE
            or (tool == "mcp__github__pull_request_review_write"
                and args.get("method") in ("create", "submit_pending"))
        ):
            deny("The GitHub server appends a Claude attribution footer to this text and the "
                 "tools can't edit it afterwards, which CLAUDE.md forbids. Don't post it; give "
                 "the text to the user to post themselves.")
        return

    if event.get("hook_event_name") == "PostToolUse" and tool in FIX_AFTER:
        if tool == "mcp__github__issue_write" and args.get("method") != "create":
            return
        print(json.dumps({
            "decision": "block",
            "reason": "The GitHub server appended a 'Generated by Claude Code' footer to what "
                      f"was just created. Remove it now: call {FIX_AFTER[tool]} you sent (no "
                      "footer), then read the object back and confirm the footer is gone.",
        }))


if __name__ == "__main__":
    main()
